# winwrap.def's exports that are winwrap's own API rather than a stand-in for a
# Win32 function, and so have no WINWRAP_REDIRECT line to take an argument size
# from. The number is the __stdcall argument bytes; None is __cdecl, which
# carries no suffix. read_own_exports() fails if winwrap.def gains one that is
# not listed here, so this cannot fall behind quietly.
OWN_EXPORTS = {
    'DllGetVersion': 4,
    'GetRealNTVersion': None,
    'GetWinWrapVersion': None,
    'IsRunningOnWine': None,
    'winwrap_RegGetValueFallbackW': 28,
}

DEF_SOURCE = os.path.join(ROOT, 'src', 'winwrap.def')

GNU_DEF_HEADER = """; Copyright 2026 Alex313031. All rights reserved.
; Use of this source code is governed by a BSD-style license that can be
; found in the LICENSE file.
;
; GENERATED by tools/gen_forwarders.py from src/static_redirects.cc and
; src/winwrap.def. Do not edit. Change those and re-run the generator.
;
; winwrap.def for the 32-bit MinGW build, with every __stdcall name carrying
; its @bytes suffix. Only GNUmakefile uses it, and only for x86.
;
; winwrap.def itself writes `GetTickCount64 = ww_GetTickCount64` and leaves
; the linker to find _ww_GetTickCount64@0, which link.exe and lld-link do, and
; to give the import library a symbol decorated the way call sites reference
; it, which they also do. GNU ld does neither by itself: it wants the
; decorated name spelled out, and the import library it would write beside
; the DLL names its symbols exactly as the exports are named. So this file
; spells the decoration out, the DLL is linked from it with --kill-at to
; export the plain names Windows itself uses, and dlltool -k builds the
; import library from it with the decorated symbols a call site needs.
;
; x64 has one calling convention and no decoration, so that build uses
; winwrap.def as it stands.
"""


def read_own_exports(path):
    """The exports in winwrap.def that are not aliases, checked against OWN_EXPORTS."""
    names = []
    in_exports = False
    with open(path, encoding='utf-8') as f:
        for line in f:
            text = line.split(';', 1)[0].strip()
            if not text:
                continue
            if text.upper() == 'EXPORTS':
                in_exports = True
                continue
            if in_exports and '=' not in text:
                names.append(text.split()[0])
    unknown = sorted(set(names) - set(OWN_EXPORTS))
    if unknown:
        sys.exit('winwrap.def exports %s with no alias, and tools/gen_forwarders.py '
                 'does not know its calling convention. Add it to OWN_EXPORTS.'
                 % ', '.join(unknown))
    return names


def generate_gnu_def_x86(entries, own):
    lines = []
    for name, nbytes in entries:
        lines.append('%s@%d = ww_%s@%d' % (name, nbytes, name, nbytes))
    for name in own:
        nbytes = OWN_EXPORTS[name]
        lines.append(name if nbytes is None else '%s@%d' % (name, nbytes))
    # Sorted by exported name, as winwrap.def is.
    lines.sort(key=lambda text: text.split('@')[0].split()[0].lower())
    out = [GNU_DEF_HEADER, 'LIBRARY winwrap.dll', 'EXPORTS']
    out.extend('    ' + line for line in lines)
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='verify the generated files are current; write nothing')
    args = parser.parse_args()

    entries = read_redirects(SOURCE)
    outputs = {
        os.path.join(ROOT, 'src', 'forwarders_x86.asm'): generate_x86(entries),
        os.path.join(ROOT, 'src', 'forwarders_x64.asm'): generate_x64(entries),
        os.path.join(ROOT, 'src', 'plain_names_x86.asm'): generate_plain_x86(entries),
        os.path.join(ROOT, 'src', 'plain_names_x64.asm'): generate_plain_x64(entries),
        os.path.join(ROOT, 'src', 'winwrap_gnu_x86.def'):
            generate_gnu_def_x86(entries, read_own_exports(DEF_SOURCE)),
    }

    stale = []
    for path, content in sorted(outputs.items()):
        name = os.path.relpath(path, ROOT).replace(os.sep, '/')
        if args.check:
            current = open(path, encoding='utf-8').read() if os.path.exists(path) else None
            if current != content:
                stale.append(name)
            else:
                print('  [ok]    %s' % name)
        else:
            # Written with \r\n: these are MSVC build inputs and the rest of the
            # repository's Windows-only files use CRLF.
            with open(path, 'w', encoding='utf-8', newline='\r\n') as f:
                f.write(content)
            print('  [wrote] %-28s %d redirects + 1 anchor' % (name, len(entries)))

    if stale:
        for name in stale:
            print('  [stale] %s' % name)
        sys.exit('\n%d file(s) out of date. Run: python3 tools/gen_forwarders.py'
                 % len(stale))
    return 0


if __name__ == '__main__':
    sys.exit(main())
