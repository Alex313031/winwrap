"""Generates src/forwarders_x86.asm, src/forwarders_x64.asm, their
plain_names_<arch>.asm companions, and src/winwrap_gnu_x86.def.

The forwarders are described below. The plain_names files are the MSVC form
of src/plain_names.cc, and their own header says what they are for. The last
is winwrap.def with the x86
__stdcall decoration written out, which is the form the MinGW linker needs;
its own header says why, and GNUmakefile is its only user.

These are the MSVC form of src/static_redirects.cc. That file names its symbols
with a Clang asm label, because __imp__Foo@4 is not a legal C identifier and an
asm label is the only way to produce the name from source. MSVC has no asm
labels and no equivalent, so a pure-MSVC build cannot compile it at all -- it
reports C2059 and C2146 on every WINWRAP_REDIRECT line. MASM can name anything,
so the same table assembles instead.

A build uses one or the other, never both: two definitions of __imp_<name> is a
duplicate symbol. See the Makefile, which compiles every source except
static_redirects.cc and assembles the matching .asm in its place.

The table lives in static_redirects.cc and is read from there, so there is one
list to keep right rather than three. The outputs are checked in, so no build
system needs Python; re-run this after adding or removing a WINWRAP_REDIRECT:

    python3 tools/gen_forwarders.py          # rewrite both files
    python3 tools/gen_forwarders.py --check  # verify they are current, write nothing

On the decoration, which is the whole reason there are two files. An extern "C"
__stdcall function is _Name@bytes on x86 and Name on x64, and the slot the call
site loads through is __imp_ prefixed to that -- so __imp__Name@bytes against
__imp_Name. The pointer is 4 bytes against 8, hence dd against dq. And .model
flat is x86-only; ml64 rejects it. One file with IFDEF around all of that would
be harder to read than two generated ones, and MASM has no predefined
architecture macro to branch on anyway -- _M_IX86 is a cl.exe macro, not an
assembler one, so a hand-written IFDEF on it is always false.
"""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, 'src', 'static_redirects.cc')
ANCHOR = 'winwrap_static_redirects'

HEADER = """; Copyright 2026 Alex313031. All rights reserved.
; Use of this source code is governed by a BSD-style license that can be
; found in the LICENSE file.
;
; GENERATED by tools/gen_forwarders.py from src/static_redirects.cc.
; Do not edit. Add redirects there and re-run the generator.
;
; The MSVC form of static_redirects.cc: the same __imp_<name> slots, named in
; MASM because MSVC has no Clang asm labels to name them from C++. A build
; assembles this OR compiles static_redirects.cc, never both -- two
; definitions of a slot is a duplicate symbol.
;
; {arch_note}
;
; The body is guarded on {guard}, which the build defines for the matching
; architecture only. Both files go into every build's source list, because a
; GYP or MSBuild project holds all its configurations at once and cannot
; choose a source per architecture -- so the one that does not apply has to
; assemble to an empty object rather than be excluded. It would not merely be
; wrong otherwise: ml64 rejects .model outright, and ml would quietly accept
; the x64 file and define undecorated 8-byte slots nothing references.
"""


def read_redirects(path):
    """Returns [(name, stdcall_arg_bytes)] in source order."""
    text = open(path, encoding='utf-8').read()
    # Drop the macro definition itself, whose parameter is literally 'name'.
    text = re.sub(r'#define WINWRAP_REDIRECT.*?\n(?:.*\\\n)*.*\n', '', text)
    entries = re.findall(r'WINWRAP_REDIRECT\((\w+),\s*(\d+)\)', text)
    if not entries:
        sys.exit('error: no WINWRAP_REDIRECT entries found in %s' % path)
    # Every use has to match, not merely most of them. The pattern accepts only
    # a literal decimal count, so a redirect written with a macro or in hex
    # parses as nothing at all and its slot never reaches the .asm -- which
    # surfaces as a consumer failing to load on XP, nowhere near here. Counting
    # the uses separately is what turns a silent omission into an error.
    uses = len(re.findall(r'WINWRAP_REDIRECT\(', text))
    if uses != len(entries):
        sys.exit('error: %s has %d WINWRAP_REDIRECT uses but %d parsed; a count '
                 'that is not a literal decimal does not match'
                 % (path, uses, len(entries)))
    return [(n, int(b)) for n, b in entries]


def _neither_define_guard(other_guard, this_guard):
    """Lines that make 'no architecture define at all' an assembler error.

    Each file assembles empty when the *other* architecture is selected, which
    is intended -- both are in the GYP source list and only one body may apply.
    What must not be quiet is neither define arriving, because then both files
    assemble empty, lib succeeds, and winwrap.lib ships with no slots and no
    anchor. That has happened: the define is delivered through
    msvs_settings.MASM.PreprocessorDefinitions, which gyp's ninja generator
    does not read. Failing here costs a build; not failing costs a consumer a
    link error at best and a binary that silently redirects nothing at worst.
    """
    return [
        'IFNDEF %s' % this_guard,
        ' IFNDEF %s' % other_guard,
        '  .err <neither %s nor %s is defined; the build is not passing the '
        'architecture define to ml>' % (this_guard, other_guard),
        ' ENDIF',
        'ENDIF',
        '',
    ]


def generate_x86(entries):
    note = ('x86. Names carry a leading underscore and the __stdcall argument '
            'size, and a\n; slot is one 4-byte pointer, so dd.')
    out = [HEADER.format(arch_note=note, guard='WINWRAP_X86')]
    out.extend(_neither_define_guard('WINWRAP_X64', 'WINWRAP_X86'))
    out.append('IFDEF WINWRAP_X86')
    out.append('')
    out.append('.386')
    out.append('.model flat')
    out.append('')
    for name, nbytes in entries:
        out.append('EXTERN _ww_%s@%d : PROC' % (name, nbytes))
    out.append('')
    out.append('.data')
    out.append('')
    for name, nbytes in entries:
        sym = '__imp__%s@%d' % (name, nbytes)
        out.append('PUBLIC %s' % sym)
        out.append('%s dd _ww_%s@%d' % (sym, name, nbytes))
    out.append('')
    out.append('; The anchor a consumer names in /INCLUDE: to force this object into the')
    out.append('; link. static_redirects.cc defines the same symbol, so whichever of the two')
    out.append('; a build uses, the contract is identical.')
    out.append('PUBLIC _%s' % ANCHOR)
    out.append('_%s dd 0' % ANCHOR)
    out.append('')
    out.append('ENDIF')
    out.append('')
    # END closes the module and so sits outside the guard: a skipped body still
    # has to be a well-formed, empty translation unit.
    out.append('END')
    return '\n'.join(out) + '\n'


def generate_x64(entries):
    note = ('x64. One calling convention, so names are undecorated, and a slot '
            'is one\n; 8-byte pointer, so dq. No .model directive: ml64 rejects it.')
    out = [HEADER.format(arch_note=note, guard='WINWRAP_X64')]
    out.extend(_neither_define_guard('WINWRAP_X86', 'WINWRAP_X64'))
    out.append('IFDEF WINWRAP_X64')
    out.append('')
    for name, _ in entries:
        out.append('EXTERN ww_%s : PROC' % name)
    out.append('')
    out.append('.data')
    out.append('')
    for name, _ in entries:
        sym = '__imp_%s' % name
        out.append('PUBLIC %s' % sym)
        out.append('%s dq ww_%s' % (sym, name))
    out.append('')
    out.append('; The anchor a consumer names in /INCLUDE: to force this object into the')
    out.append('; link. static_redirects.cc defines the same symbol, so whichever of the two')
    out.append('; a build uses, the contract is identical.')
    out.append('PUBLIC %s' % ANCHOR)
    out.append('%s dd 0' % ANCHOR)
    out.append('')
    out.append('ENDIF')
    out.append('')
    # See the x86 note: END closes the module, so it is outside the guard.
    out.append('END')
    return '\n'.join(out) + '\n'


PLAIN_HEADER = """; Copyright 2026 Alex313031. All rights reserved.
; Use of this source code is governed by a BSD-style license that can be
; found in the LICENSE file.
;
; GENERATED by tools/gen_forwarders.py from src/static_redirects.cc.
; Do not edit. Add redirects there and re-run the generator.
;
; The MSVC form of plain_names.cc: every redirected function under its own
; name, as a jump to the ww_ shim, for callers that reference the function by
; name and not through its __imp_ slot. static_redirects.cc says who those
; are. A build assembles this OR compiles plain_names.cc, never both.
;
; A separate object from forwarders_<arch>.asm on purpose. That one is forced
; into every link by the anchor; this one is an ordinary archive member,
; extracted only when something references one of these names, so a consumer
; that defines one of them for itself and references none never meets it.
; static_redirects.cc says where that protection ends.
;
; {arch_note}
;
; The body is guarded on {guard}, for the reason given at length in
; forwarders_<arch>.asm: one generated project holds both architectures.
"""


def generate_plain_x86(entries):
    note = ('x86. A __stdcall name is _Name@bytes, and so is the shim it jumps '
            'to.')
    out = [PLAIN_HEADER.format(arch_note=note, guard='WINWRAP_X86')]
    out.extend(_neither_define_guard('WINWRAP_X64', 'WINWRAP_X86'))
    out.append('IFDEF WINWRAP_X86')
    out.append('')
    out.append('.386')
    out.append('.model flat')
    out.append('')
    for name, nbytes in entries:
        out.append('EXTERN _ww_%s@%d : PROC' % (name, nbytes))
    out.append('')
    out.append('.code')
    out.append('')
    for name, nbytes in entries:
        sym = '_%s@%d' % (name, nbytes)
        out.append('PUBLIC %s' % sym)
        out.append('%s PROC' % sym)
        out.append('    jmp _ww_%s@%d' % (name, nbytes))
        out.append('%s ENDP' % sym)
    out.append('')
    out.append('ENDIF')
    out.append('')
    out.append('END')
    return '\n'.join(out) + '\n'


